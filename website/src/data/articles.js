// Rough reading time at ~200 words a minute.
export function readingTime(article) {
  const words = article.body
    .flatMap(([, content]) => (Array.isArray(content) ? content : [content]))
    .join(' ')
    .split(/\s+/).length;
  return Math.max(1, Math.round(words / 200));
}

